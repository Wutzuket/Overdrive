package de.wutzuket.overdrive.sound;

import de.wutzuket.overdrive.Overdrive;
import net.minecraft.core.registries.Registries;
import net.minecraft.sounds.SoundEvent;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * All sound events of the mod.
 *
 * The location of a sound event has to match the key of the matching entry in
 * {@code assets/overdrive/sounds.json}, because the client looks the sound file
 * up by the location of the sound event and not by the name of the registry
 * entry.
 *
 * The sound files themselves are generated by
 * {@code tools/generate_machine_sounds.py}.
 */
public final class ODSounds {
    public static final DeferredRegister<SoundEvent> SOUND_EVENTS =
            DeferredRegister.create(Registries.SOUND_EVENT, Overdrive.MODID);

    /**
     * The base volume of a running machine. The config value only scales it, so
     * that the level stays the same even with an old config file.
     */
    public static final float BASE_VOLUME = 0.3F;
    /** The base volume of the one-shot of the circuit press. */
    public static final float PRESS_VOLUME = 0.55F;

    /** Burning coal, played while the generator burns fuel. */
    public static final DeferredHolder<SoundEvent, SoundEvent> COAL_GENERATOR = register("machine.coal_generator");
    /** Hum of the particle accelerator while it accelerates particles. */
    public static final DeferredHolder<SoundEvent, SoundEvent> PARTICLE_ACCELERATOR = register("machine.particle_accelerator");
    /** Hum of the AD ring while it runs. */
    public static final DeferredHolder<SoundEvent, SoundEvent> AD_RING = register("machine.ad_ring");
    /** Hum of the ELENA ring while it runs. */
    public static final DeferredHolder<SoundEvent, SoundEvent> ELENA_RING = register("machine.elena_ring");
    /** Electrical discharge of the electron gun. */
    public static final DeferredHolder<SoundEvent, SoundEvent> ELECTRON_GUN = register("machine.electron_gun");
    /** Cold air of the cryo distiller while it distils. */
    public static final DeferredHolder<SoundEvent, SoundEvent> CRYO_DISTILLER = register("machine.cryo_distiller");
    /** Motor of the vacuum pump while it evacuates or holds the vacuum. */
    public static final DeferredHolder<SoundEvent, SoundEvent> VACUUM_PUMP = register("machine.vacuum_pump");
    /** Rumble of the annihilation reactor while it burns antimatter. */
    public static final DeferredHolder<SoundEvent, SoundEvent> ANNIHILATION_REACTOR = register("machine.annihilation_reactor");
    /** Air of the cooling tower while it processes fluids. */
    public static final DeferredHolder<SoundEvent, SoundEvent> COOLING_TOWER = register("machine.cooling_tower");
    /** One-shot of the circuit press, played at the end of a craft cycle. */
    public static final DeferredHolder<SoundEvent, SoundEvent> CIRCUIT_PRESS = register("machine.circuit_press");

    private ODSounds() {
    }

    private static DeferredHolder<SoundEvent, SoundEvent> register(String name) {
        return SOUND_EVENTS.register(name,
                () -> SoundEvent.createVariableRangeEvent(Overdrive.id(name)));
    }

    public static void register(IEventBus modEventBus) {
        SOUND_EVENTS.register(modEventBus);
    }
}
